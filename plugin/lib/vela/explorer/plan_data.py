"""The build plan, as the page draws it: each team's work breakdown read beside the vault and its design.

    plans_for(["APP-booking=../booking/docs/plan/booking-breakdown.md", ...]) -> {app ID: {path, read}}
    inside(vault, keys, plans, designs) -> {app key: plan, with what the page draws from it}

Level 4 of "Inside this app" (DESIGN-INSIDE.md). The file is docs/plan/<slug>-breakdown.md, written by the
work-breakdown skill and read by vela/breakdown.py, the same reader tools/breakdown_to_tickets.py uses. This module
adds what only the page needs, and each is worked out here so it can be tested without a browser:

- what blocks a story: another story, an open vault question (the page lights the story with that question's lamp),
  an outside party, a question or gap only the plan names, or words nothing here can classify (`kind` says which);
- coverage, computed from the stories' own "Traces to" lines and their tasks' components, then held against the
  plan's Coverage table and the design's components, so an empty cell is the plan's failure and not a rounding;
- the Jira CSV, generated by breakdown.csv_text so "Copy as Jira CSV" is the file the tool writes, byte for byte.

A disagreement between two parts of the plan (a size total that is not its tasks, a Coverage table that omits a
target a story traces) is a line in `problems`, shown on the page and never fixed up. Only a missing file or an
argument that is not `APP-x=path` raises PlanError: a plan the caller asked for must not quietly become "no plan".
"""
import pathlib
import re

from vela import breakdown, slices, tickets

from . import breakdown_find, design_data

TICKETS = "tickets.csv"
OUTSIDE = re.compile(r"\b(?:outside party|outside|vendor|third[- ]party|external|supplier)\b", re.I)
PLAN_QUESTION = re.compile(r"\b(?:OQ|Q)-\d+\b|\bopen question\b", re.I)
GAP_OR_DEFERRAL = re.compile(r"\b(?:GAP|G|D|DEF)-?\d+\b|\bgap\b|\bdeferred\b", re.I)
VAULT_QUESTION = re.compile(r"\bUNK-\d{3}\b")
APP_ONLY = re.compile(r"^APP-[A-Za-z0-9-]+$")
SIZES = tuple(breakdown.SIZE_POINTS)
# Words a release story's Component cell uses for work that is not one design component: "all" (every one), "packaging".
PLAN_WIDE = ("all", "packaging")
EPIC_CRITERION = re.compile(r"\bEPC-\d+\.AC\d+\b")


class PlanError(Exception):
    """The caller named a breakdown that cannot be read at all."""


def plans_for(args):
    """{app ID: {path, read}} for each `APP-x=path` argument, as `--breakdown` and breakdown_find pass them."""
    out = {}
    for arg in args or []:
        match = design_data.SPEC.match(arg.strip())
        if not match:
            raise PlanError(f"--breakdown takes APP-x=path, not {arg!r}")
        app, where = match.group(1), pathlib.Path(match.group(2))
        if app in out:
            raise PlanError(f"--breakdown names {app} twice")
        if not where.is_file():
            raise PlanError(f"no breakdown at {where}")
        try:
            text = where.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            raise PlanError(f"cannot read {where}: {exc}") from exc
        out[app] = {"path": where, "read": breakdown.read(text)}
    return out


def tickets_path(plan_path):
    """The tickets CSV the tool wrote for this plan, if it is there: docs/work/ (the tool's default) or the plan's folder."""
    plan_path = pathlib.Path(plan_path).resolve()
    for candidate in (plan_path.parent.parent / "work" / TICKETS, plan_path.parent / TICKETS):
        if candidate.is_file():
            return candidate
    return None


# ---------------------------------------------------------------- what blocks a story

PLAN_IDS = re.compile(r"\b(?:OQ|Q)-\d+\b")
GAP_IDS = re.compile(r"\b(?:GAP|G|D|DEF|PG)-\d+\b")
ANY_ID = re.compile(r"\b[A-Z]{1,5}-\d+[a-z]?\b")  # an ID-like token, such as UNK-777 or CST-010


def segments(text):
    """The parts of a Blocked by line, split at commas and semicolons that are not inside parentheses."""
    parts, depth, current = [], 0, ""
    for ch in text or "":
        depth += (ch == "(") - (ch == ")")
        if ch in ",;" and depth <= 0:
            parts.append(current)
            current = ""
        else:
            current += ch
    parts.append(current)
    return [p.strip() for p in parts if p.strip()]


def blockers_of(text, known):
    """[{kind, ref, text}] for a story's Blocked by line. `known` is the vault's IDs, so UNK-nnn is a vault question
    only when the vault holds it. Kinds: story, question (in the vault), outside, plan-question (named only by the plan),
    gap (a gap or deferral), other (nothing here can say what it is, and the page says so)."""
    out = []
    if breakdown.NO_BLOCKERS.match(text or ""):
        return out  # "none. D-001 runs in parallel, not a gate": nothing blocks the story; blockedText keeps the note
    for part in segments(text):
        if breakdown.NOTHING.match(part):
            continue
        stories = breakdown.story_refs(part)
        vault_q = [q for q in VAULT_QUESTION.findall(part) if q in known]
        if stories:
            out += [{"kind": "story", "ref": s, "text": s} for s in stories]
        elif vault_q:
            out += [{"kind": "question", "ref": q, "text": part} for q in vault_q]
        elif OUTSIDE.search(part):
            out.append({"kind": "outside", "ref": "", "text": part})
        elif PLAN_QUESTION.search(part) or GAP_OR_DEFERRAL.search(part):
            # The design's own open questions (OQ-nnn) and deferrals (D-nnn): one node per ID, named by it, so the same
            # question named in three clauses of one story is one node, not three.
            for kind, ids in (("plan-question", PLAN_IDS.findall(part)), ("gap", GAP_IDS.findall(part))):
                out += [{"kind": kind, "ref": i, "text": part} for i in ids]
            if not PLAN_IDS.search(part) and not GAP_IDS.search(part):
                out.append({"kind": "plan-question" if PLAN_QUESTION.search(part) else "gap", "ref": "", "text": part})
        elif ANY_ID.search(part):
            out.append({"kind": "other", "ref": "", "text": part})
        # Otherwise the part is only words, a clause of the sentence ("so confirm with the owner", "not decided
        # here"): it is not a blocker, and the story's blockedText keeps the whole sentence for the reader.
    seen, unique = set(), []
    for b in out:  # one node per thing named: a question named in two clauses of the same line is one blocker
        key = (b["kind"], b["ref"] or b["text"])
        if key not in seen:
            seen.add(key)
            unique.append(b)
    return unique


# ---------------------------------------------------------------- coverage

def base(target):
    """A trace target without its @APP suffix: the plan is one app's, so CAP-013.FR1 and CAP-013.FR1@APP-x are one."""
    return target.split("@")[0]


def traced_ids(text):
    return list(dict.fromkeys(i.rstrip("-") for i in breakdown.VAULT_ID.findall(text or "") if not APP_ONLY.match(i)))


def aliases(name):
    """A component's names: "CallClassifier and ClientMatcher" is one design component that tasks name together or apart."""
    return [name] + [p.strip() for p in re.split(r",|\band\b", name) if p.strip()] if re.search(r",|\band\b", name) else [name]


def names_component(cell, name):
    return any(re.search(rf"(?<![\w-]){re.escape(alias)}(?![\w-])", cell or "", re.I) for alias in aliases(name))


def names_no_component(cell, known):
    """True when a task's Component cell holds a part that is neither plan-wide nor any design component."""
    parts = [p.strip() for p in re.split(r",|\band\b", cell or "") if p.strip()]
    return any(p.lower() not in PLAN_WIDE and not any(names_component(p, n) for n in known) for p in parts)


def coverage(stories, table, design, problems):
    """{targets, components}: [{target|name, stories, stated}] with `stories` the stories that cover it by their own lines."""
    stated = {}
    for r in table:  # one target can have several rows ("(share)", "(obligation of CON-001)"): its stories are all of them
        key = base(r["id"]) if r["id"] else r["target"]
        stated[key] = {"stories": list(dict.fromkeys([*stated.get(key, {"stories": []})["stories"], *r["stories"]]))}
    owned = [] if design is None else [e["id"] for name, entries in design["trace"].items() if name != "Operations" for e in entries]
    order = list(dict.fromkeys([*(r["id"] for r in table if r["id"]), *owned,
                                *(t for s in stories for t in s["traces"])]))
    targets = []
    for target in order:
        by_lines = [s["id"] for s in stories if base(target) in {base(t) for t in s["traces"]}]
        row = stated.get(base(target))
        said = row["stories"] if row else None
        if row is None and by_lines:
            problems.append(f"{', '.join(by_lines)} traces to {target}, but the Coverage table has no row for it")
        elif said is not None and not set(said) <= set(by_lines):  # a story may trace more than the table credits it with; the table must not credit one that does not trace it
            problems.append(f"the Coverage table gives {target} to {', '.join(said) or 'no story'}, but the stories that trace to it are {', '.join(by_lines) or 'none'}")
        targets.append({"target": target, "stories": by_lines, "stated": said})
    names = [c["name"] for c in design["components"]] if design else []
    names += [r["target"] for r in table if not r["id"] and r["target"].lower() not in {n.lower() for n in names}]
    components = []
    for name in names:
        by_tasks = [s["id"] for s in stories if any(names_component(t["component"], name) for t in s["tasks"])]
        row = stated.get(base(name))
        components.append({"name": name, "stories": by_tasks, "stated": row["stories"] if row else None})
    if design:
        known = {n.lower() for n in names}
        for s in stories:
            for t in s["tasks"]:
                if t["component"] and names_no_component(t["component"], known):
                    problems.append(f"{s['id']} task {t['name']!r} names component {t['component']!r}, which is not a component of the design")
    return {"targets": targets, "components": components}


# ---------------------------------------------------------------- one plan

def story_entry(story, summary, order_of, known, problems, tracer_slice=""):
    """One story as plain data, held against the summary table's row for it."""
    tasks = [{"name": r[0], "size": (r[1] if len(r) > 1 else "").strip().upper(), "component": r[2] if len(r) > 2 else "",
              "points": breakdown.SIZE_POINTS.get((r[1] if len(r) > 1 else "").strip().upper(), 0)} for r in story.tasks]
    entry = {"id": story.id, "name": story.name, "order": order_of.get(story.id), "traces": traced_ids(story.traces), "tracesText": story.traces or "",
             "size": breakdown.size_total(story), "points": breakdown.points(story), "state": story.state, "slice": story.slice, "sliceId": story.slice_id,
             "tracer": story.tracer or story.slice == "tracer" or bool(tracer_slice and story.slice_id == tracer_slice),
             "doneWhen": story.done_when or "", "components": story.components or "", "fit": story.fit or "", "criteria": story.criteria, "criteriaLabel": story.criteria_label, "openNotes": story.open_notes,
             "conflicts": [{"text": c, "ref": (EPIC_CRITERION.findall(c) or [""])[0]} for c in story.conflicts], "tasks": tasks,
             "blockedText": story.blocked or "", "blockers": [b for b in blockers_of(story.blocked, known) if b["ref"] != story.id]}  # a note that names its own story ("S-06 must not ship before S-11") does not make it wait for itself
    row = summary.get(story.id)
    if row and story.built:
        if breakdown.size_counts(row["size"]) != breakdown.size_counts(entry["size"]):
            problems.append(f"{story.id}: the summary table says its size is {row['size']!r}, but its tasks add up to {entry['size']}")
        if not {base(t) for t in traced_ids(row["traces"])} <= {base(t) for t in entry["traces"]}:  # the table abbreviates ("FR1 and FR4 shares"); it must not name a target the section does not
            problems.append(f"{story.id}: the summary table and the story section disagree on what it delivers (Traces to)")
        if not set(breakdown.story_refs(row["blocked"])) <= set(breakdown.story_refs(story.blocked)):
            problems.append(f"{story.id}: the summary table and the story section disagree on what it waits for (Blocked by)")
    return entry


def totals(stories):
    """Counts over the stories the team will build: a deferred or merged story keeps its tasks on the page but is in no total."""
    by_size = {size: {"tasks": 0, "points": 0} for size in SIZES}
    built = [s for s in stories if s["state"] not in breakdown.NOT_BUILT]
    for s in built:
        for t in s["tasks"]:
            if t["size"] in by_size:
                by_size[t["size"]]["tasks"] += 1
                by_size[t["size"]]["points"] += t["points"]
    return {"stories": len(stories), "built": len(built), "tasks": sum(len(s["tasks"]) for s in built), "points": sum(s["points"] for s in built), "bySize": by_size}


def plan_entry(app_id, wrapped, known, design, tracer_slice=""):
    read, path = wrapped["read"], wrapped["path"]
    problems = list(read["problems"])
    order = read["order"]
    order_of = {o["id"]: i + 1 for i, o in enumerate(order)}
    ranked = sorted(read["stories"], key=lambda s: order_of.get(s.id, len(order) + 1))
    stories = [story_entry(s, read["summary"], order_of, known, problems, tracer_slice) for s in ranked]
    if design and design["path"] not in breakdown_find.prereq_names(read["meta"]):
        problems.append(f"the plan's prereqs do not name the design doc {design['path']}, so it may be a plan for another design")
    gaps = [{"id": str(g.get("id", "")), "note": str(g.get("note") or g.get("what") or "")} for g in read["meta"].get("gaps") or [] if isinstance(g, dict)]
    cover = coverage(stories, read["coverage"], design, problems)
    unresolved = [{"id": t, "story": s["id"]} for s in stories for t in s["traces"] if t not in known and not t.startswith("FR-")]
    return {"appId": app_id, "file": path.name, "slug": str(read["meta"].get("slug", "")), "status": str(read["meta"].get("status", "")), "gaps": gaps,
            "prereqs": breakdown_find.prereq_names(read["meta"]), "stories": stories, "order": order, "coverage": cover, "notPlanned": read["not_planned"],
            "totals": totals(stories), "problems": problems, "unresolved": unresolved, "ticketsHref": "",
            "csv": tickets.csv_for(ranked, tickets.Context(ranked))}


def inside(vault, keys, plans, designs):
    """{app key: plan} for each `--breakdown`, with what the page draws: blockers, coverage, totals and the CSV."""
    known = design_data.vault_ids(vault)
    by_id = {a.id: a for a in vault.apps}
    by_app = {d["appId"]: d for d in designs.values()}
    # A story is the tracer's when it says so, or when it names the vault's tracer slice: the tag reads from slices
    tracer = slices.tracer(slices.read_slices(vault)) if plans else None
    tracer_id = tracer.id if tracer is not None else ""
    out = {}
    for app_id, wrapped in plans.items():
        app = by_id.get(app_id)
        if app is None:
            raise PlanError(f"--breakdown names {app_id}, which is not an app in this vault")
        out[keys.page(app)] = plan_entry(app_id, wrapped, known, by_app.get(app_id), tracer_id)
    return out
